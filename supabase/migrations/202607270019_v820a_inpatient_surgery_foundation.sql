  surgery_code text,
  body_site text,

  status text not null default 'scheduled'
    check (
      status in (
        'scheduled',
        'preparing',
        'anesthesia',
        'in_surgery',
        'recovery',
        'completed',
        'cancelled'
      )
    ),

