-- ---------------------------------------------------------
-- 10. updated_at 자동 갱신
-- ---------------------------------------------------------
create or replace function public.pawu_touch_inpatient_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists hospitalizations_touch_updated_at
  on public.hospitalizations;

create trigger hospitalizations_touch_updated_at
before update on public.hospitalizations
for each row
execute function public.pawu_touch_inpatient_updated_at();

drop trigger if exists hospitalization_events_touch_updated_at
  on public.hospitalization_events;

create trigger hospitalization_events_touch_updated_at
before update on public.hospitalization_events
for each row
execute function public.pawu_touch_inpatient_updated_at();

drop trigger if exists hospitalization_care_plans_touch_updated_at
  on public.hospitalization_care_plans;

