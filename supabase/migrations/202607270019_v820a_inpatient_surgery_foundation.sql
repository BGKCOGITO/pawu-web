  surgery_started_at timestamptz,
  surgery_ended_at timestamptz,
  recovery_started_at timestamptz,
  completed_at timestamptz,

  primary_surgeon_user_id uuid
    references auth.users(id)
    on delete set null,

  anesthetist_user_id uuid
    references auth.users(id)
    on delete set null,

  anesthesia_type text,
  anesthesia_note text,

  preoperative_diagnosis text,
  postoperative_diagnosis text,
  procedure_note text,
  findings text,
  complications text,
  recovery_status text,

  estimated_blood_loss_ml numeric,
  specimen_collected boolean not null default false,

  internal_note text,
  guardian_summary text,
  is_guardian_visible boolean not null default false,

  created_by uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

