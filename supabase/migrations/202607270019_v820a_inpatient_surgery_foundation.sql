-- ---------------------------------------------------------
-- 1. 입원 기록
-- ---------------------------------------------------------
create table if not exists public.hospitalizations (
  id bigint generated by default as identity primary key,

  hospital_id bigint not null
    references public.hospitals(id)
    on delete cascade,

  medical_record_id bigint
    references public.medical_records(id)
    on delete set null,

  hospital_patient_id bigint not null
    references public.hospital_patients(id)
    on delete cascade,

  reservation_id bigint
    references public.reservations(id)
    on delete set null,

  status text not null default 'admitted'
    check (
      status in (
        'planned',
        'admitted',
        'in_treatment',
        'recovering',
        'ready_for_discharge',
        'discharged',
        'cancelled'
      )
    ),

  admission_reason text not null,
  ward_name text,
  cage_number text,

  admitted_at timestamptz not null default now(),
  expected_discharge_at timestamptz,
  discharged_at timestamptz,

  attending_vet_user_id uuid
    references auth.users(id)
    on delete set null,

  assigned_staff_user_id uuid
    references auth.users(id)
    on delete set null,

  risk_level text not null default 'standard'
    check (
      risk_level in (
        'standard',
        'watch',
        'high',
        'critical'
      )
    ),

  isolation_required boolean not null default false,
  fasting_required boolean not null default false,

  internal_note text,
  guardian_summary text,
  is_guardian_visible boolean not null default false,

  created_by uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists hospitalizations_hospital_status_idx
  on public.hospitalizations(
    hospital_id,
    status,
    admitted_at desc
  );

create index if not exists hospitalizations_patient_idx
  on public.hospitalizations(
    hospital_patient_id,
    admitted_at desc
  );

create index if not exists hospitalizations_record_idx
  on public.hospitalizations(
    medical_record_id,
    admitted_at desc
  );


-- ---------------------------------------------------------
-- 2. 입원 이벤트 및 간호기록
-- ---------------------------------------------------------
create table if not exists public.hospitalization_events (
  id bigint generated by default as identity primary key,

  hospitalization_id bigint not null
    references public.hospitalizations(id)
    on delete cascade,

  event_type text not null
    check (
      event_type in (
        'vital',
        'meal',
        'water',
        'medication',
        'injection',
        'iv',
        'urination',
        'defecation',
        'vomiting',
        'pain',
        'wound',
        'mobility',
        'behavior',
        'procedure',
        'round',
        'guardian_update',
        'other'
      )
    ),

  occurred_at timestamptz not null default now(),

  title text not null,
  content text,

  temperature_c numeric,
  heart_rate_bpm integer,
  respiratory_rate_bpm integer,
  systolic_bp integer,
  diastolic_bp integer,
  weight_kg numeric,
  pain_score integer
    check (
      pain_score is null
      or pain_score between 0 and 10
    ),

  amount_value numeric,
  amount_unit text,

  status_value text,
  abnormal_flag boolean not null default false,
  requires_follow_up boolean not null default false,

  recorded_by uuid
    references auth.users(id)
    on delete set null,

  is_guardian_visible boolean not null default false,
  guardian_message text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists hospitalization_events_timeline_idx
  on public.hospitalization_events(
    hospitalization_id,
    occurred_at desc
  );

create index if not exists hospitalization_events_followup_idx
  on public.hospitalization_events(
    hospitalization_id,
    requires_follow_up,
    occurred_at desc
  );


