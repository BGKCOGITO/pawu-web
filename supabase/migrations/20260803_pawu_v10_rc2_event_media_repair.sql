create table if not exists public.pet_health_event_attachments (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.pet_health_events(id) on delete cascade,
  pet_id bigint not null references public.pets(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null unique,
  file_name text not null,
  mime_type text not null,
  media_type text not null check (media_type in ('image', 'video')),
  size_bytes bigint,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.pet_health_event_attachments
  add column if not exists event_id bigint references public.pet_health_events(id) on delete cascade,
  add column if not exists pet_id bigint references public.pets(id) on delete cascade,
  add column if not exists user_id uuid references auth.users(id) on delete cascade,
  add column if not exists storage_path text,
  add column if not exists file_name text,
  add column if not exists mime_type text,
  add column if not exists media_type text,
  add column if not exists size_bytes bigint,
  add column if not exists sort_order integer not null default 0,
  add column if not exists created_at timestamptz not null default now();

create unique index if not exists pet_health_event_attachments_storage_path_uidx
  on public.pet_health_event_attachments(storage_path);
create index if not exists pet_health_event_attachments_event_idx
  on public.pet_health_event_attachments(event_id, sort_order, created_at);
create index if not exists pet_health_event_attachments_pet_idx
  on public.pet_health_event_attachments(pet_id, created_at desc);

alter table public.pet_health_event_attachments enable row level security;

drop policy if exists "guardians read own event attachments" on public.pet_health_event_attachments;
create policy "guardians read own event attachments"
on public.pet_health_event_attachments for select
using (auth.uid() = user_id);

drop policy if exists "guardians insert own event attachments" on public.pet_health_event_attachments;
create policy "guardians insert own event attachments"
on public.pet_health_event_attachments for insert
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.pet_health_events e
    where e.id = event_id and e.pet_id = pet_id and e.user_id = auth.uid()
  )
);

drop policy if exists "guardians delete own event attachments" on public.pet_health_event_attachments;
create policy "guardians delete own event attachments"
on public.pet_health_event_attachments for delete
using (auth.uid() = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'pet-health-events', 'pet-health-events', false, 52428800,
  array['image/jpeg','image/png','image/webp','image/heic','image/heif','video/mp4','video/quicktime','video/webm']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "guardians read own event media" on storage.objects;
create policy "guardians read own event media"
on storage.objects for select
using (bucket_id = 'pet-health-events' and split_part(name, '/', 1) = auth.uid()::text);

drop policy if exists "guardians upload own event media" on storage.objects;
create policy "guardians upload own event media"
on storage.objects for insert
with check (bucket_id = 'pet-health-events' and split_part(name, '/', 1) = auth.uid()::text);

drop policy if exists "guardians delete own event media" on storage.objects;
create policy "guardians delete own event media"
on storage.objects for delete
using (bucket_id = 'pet-health-events' and split_part(name, '/', 1) = auth.uid()::text);

notify pgrst, 'reload schema';
