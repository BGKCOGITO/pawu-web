drop policy if exists "hospital members read dispensing jobs"
  on public.dispensing_jobs;
create policy "hospital members read dispensing jobs"
on public.dispensing_jobs
for select to authenticated
using (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = dispensing_jobs.hospital_id
      and hs.is_active = true
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = dispensing_jobs.hospital_id
  )
);

drop policy if exists "hospital members read dispensing items"
  on public.dispensing_items;
create policy "hospital members read dispensing items"
on public.dispensing_items
for select to authenticated
using (
  exists(
    select 1 from public.dispensing_jobs dj
    where dj.id = dispensing_items.dispensing_job_id
      and (
        exists(
          select 1 from public.hospital_staff hs
          where hs.user_id = auth.uid()
            and hs.hospital_id = dj.hospital_id
            and hs.is_active = true
        )
        or exists(
          select 1 from public.hospital_admins ha
          where ha.user_id = auth.uid()
            and ha.hospital_id = dj.hospital_id
        )
      )
  )
);

drop policy if exists "hospital members read dispensing logs"
  on public.dispensing_audit_logs;
create policy "hospital members read dispensing logs"
on public.dispensing_audit_logs
for select to authenticated
using (
  exists(
    select 1 from public.dispensing_jobs dj
    where dj.id = dispensing_audit_logs.dispensing_job_id
      and (
        exists(
          select 1 from public.hospital_staff hs
          where hs.user_id = auth.uid()
            and hs.hospital_id = dj.hospital_id
            and hs.is_active = true
        )
        or exists(
          select 1 from public.hospital_admins ha
          where ha.user_id = auth.uid()
            and ha.hospital_id = dj.hospital_id
        )
      )
  )
);

