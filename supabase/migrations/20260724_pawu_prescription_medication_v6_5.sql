create or replace function public.pawu_reopen_prescription(
  p_hospital_id bigint,
  p_prescription_id bigint,
  p_actor_user_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
begin
  if coalesce(trim(p_reason), '') = '' then
    raise exception '재개 사유가 필요합니다.';
  end if;

  select status
  into v_status
  from public.prescriptions
  where id = p_prescription_id
    and hospital_id = p_hospital_id
  for update;

  if not found then
    raise exception '처방전을 찾지 못했습니다.';
  end if;

  if v_status <> 'finalized' then
    raise exception '확정된 처방전만 다시 열 수 있습니다.';
  end if;

  update public.prescriptions
  set status = 'draft',
      finalized_at = null,
      finalized_by = null,
      updated_by = p_actor_user_id,
      updated_at = now()
  where id = p_prescription_id;

  insert into public.prescription_audit_logs(
    prescription_id, action, reason, actor_user_id
  )
  values(
    p_prescription_id, 'reopened', p_reason, p_actor_user_id
  );

  return jsonb_build_object(
    'prescription_id', p_prescription_id,
    'status', 'draft'
  );
end;
$$;

