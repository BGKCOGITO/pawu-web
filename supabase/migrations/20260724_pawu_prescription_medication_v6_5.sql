drop policy if exists "hospital and guardian read prescriptions"
  on public.prescriptions;

create policy "hospital and guardian read prescriptions"
on public.prescriptions
for select
to authenticated
using (
  exists(
    select 1
    from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = prescriptions.hospital_id
      and hs.is_active = true
  )
  or exists(
    select 1
    from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = prescriptions.hospital_id
  )
  or exists(
    select 1
    from public.pets p
    where p.id = prescriptions.pet_id
      and p.user_id = auth.uid()
      and prescriptions.status = 'finalized'
      and prescriptions.guardian_visible = true
  )
);

drop policy if exists "hospital and guardian read prescription items"
  on public.prescription_items;

create policy "hospital and guardian read prescription items"
on public.prescription_items
for select
to authenticated
using (
  exists(
    select 1
    from public.prescriptions pr
    join public.pets p on p.id = pr.pet_id
    where pr.id = prescription_items.prescription_id
      and (
        exists(
          select 1
          from public.hospital_staff hs
          where hs.user_id = auth.uid()
            and hs.hospital_id = pr.hospital_id
            and hs.is_active = true
        )
        or exists(
          select 1
          from public.hospital_admins ha
          where ha.user_id = auth.uid()
            and ha.hospital_id = pr.hospital_id
        )
        or (
          p.user_id = auth.uid()
          and pr.status = 'finalized'
          and pr.guardian_visible = true
        )
      )
  )
);

drop policy if exists "hospital members read prescription templates"
