do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'reservations_status_v2_check'
  ) then
    alter table public.reservations
      drop constraint if exists reservations_status_check;
    alter table public.reservations
      add constraint reservations_status_v2_check
      check (status in ('requested','approved','arrived','in_progress','payment_pending','completed','rejected','cancelled','no_show'));
  end if;
exception when others then
  raise notice '예약 status 제약조건은 기존 프로젝트 설정에 맞게 수동 확인이 필요할 수 있습니다: %', sqlerrm;
