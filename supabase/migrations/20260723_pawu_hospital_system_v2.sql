drop policy if exists "hospital staff read coworkers" on public.hospital_staff;
create policy "hospital staff read coworkers" on public.hospital_staff for select to authenticated
using (exists(select 1 from public.hospital_staff me where me.user_id=auth.uid() and me.hospital_id=hospital_staff.hospital_id and me.is_active=true));

drop policy if exists "hospital owners manage staff" on public.hospital_staff;
create policy "hospital owners manage staff" on public.hospital_staff for all to authenticated
using (exists(select 1 from public.hospital_staff me where me.user_id=auth.uid() and me.hospital_id=hospital_staff.hospital_id and me.role='owner' and me.is_active=true))
with check (exists(select 1 from public.hospital_staff me where me.user_id=auth.uid() and me.hospital_id=hospital_staff.hospital_id and me.role='owner' and me.is_active=true));

drop policy if exists "hospital and guardian read exams" on public.medical_exams;
create policy "hospital and guardian read exams" on public.medical_exams for select to authenticated
using (
  exists(select 1 from public.pets p where p.id=medical_exams.pet_id and p.user_id=auth.uid())
  or exists(select 1 from public.hospital_staff hs where hs.user_id=auth.uid() and hs.hospital_id=medical_exams.hospital_id and hs.is_active=true)
);

drop policy if exists "hospital and guardian read surgeries" on public.surgery_records;
