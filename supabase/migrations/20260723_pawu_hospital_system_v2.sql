create table if not exists public.hospital_staff (
  id bigint generated by default as identity primary key,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null,
  email text not null,
  role text not null check (role in ('owner','veterinarian','nurse','receptionist')),
  permissions jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  invited_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(hospital_id,user_id)
);

create table if not exists public.medical_exams (
  id bigint generated by default as identity primary key,
  medical_record_id bigint references public.medical_records(id) on delete set null,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  pet_id bigint not null references public.pets(id) on delete cascade,
  exam_type text not null,
  exam_name text not null,
  result_summary text,
  result_detail text,
  performed_at date not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.surgery_records (
  id bigint generated by default as identity primary key,
  medical_record_id bigint references public.medical_records(id) on delete set null,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  pet_id bigint not null references public.pets(id) on delete cascade,
  surgery_name text not null,
  procedure_notes text,
  surgeon_name text,
  anesthesia_notes text,
  performed_at date not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.medical_attachments (
  id bigint generated by default as identity primary key,
  medical_record_id bigint references public.medical_records(id) on delete set null,
  exam_id bigint references public.medical_exams(id) on delete set null,
  surgery_id bigint references public.surgery_records(id) on delete set null,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  pet_id bigint not null references public.pets(id) on delete cascade,
  uploaded_by uuid references auth.users(id) on delete set null,
  file_name text not null,
  file_path text not null,
  file_type text not null,
  mime_type text,
  file_size bigint,
  public_url text,
  created_at timestamptz not null default now()
);

create index if not exists hospital_staff_user_idx on public.hospital_staff(user_id,is_active);
create index if not exists medical_exams_pet_date_idx on public.medical_exams(pet_id,performed_at desc);
create index if not exists surgery_records_pet_date_idx on public.surgery_records(pet_id,performed_at desc);
create index if not exists medical_attachments_pet_idx on public.medical_attachments(pet_id,created_at desc);

