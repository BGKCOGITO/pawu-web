drop policy if exists "hospital members read inventory items" on public.inventory_items;
create policy "hospital members read inventory items"
on public.inventory_items for select to authenticated
using (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = inventory_items.hospital_id
      and hs.is_active = true
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = inventory_items.hospital_id
  )
);

drop policy if exists "hospital managers manage inventory items" on public.inventory_items;
create policy "hospital managers manage inventory items"
on public.inventory_items for all to authenticated
using (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = inventory_items.hospital_id
      and hs.is_active = true
      and (
        coalesce(hs.role, '') = 'owner'
        or coalesce((hs.permissions->>'manage_inventory')::boolean, false)
      )
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = inventory_items.hospital_id
  )
)
with check (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = inventory_items.hospital_id
      and hs.is_active = true
      and (
        coalesce(hs.role, '') = 'owner'
        or coalesce((hs.permissions->>'manage_inventory')::boolean, false)
      )
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = inventory_items.hospital_id
  )
);

