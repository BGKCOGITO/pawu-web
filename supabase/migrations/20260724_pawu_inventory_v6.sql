-- 중요:
-- 재고 수량 변경은 클라이언트에서 직접 UPDATE 하지 않고
-- 서버 API가 pawu_apply_inventory_movement RPC를 호출해 원자적으로 처리합니다.
-- V6에서는 진료 항목과 예상 재고 사용량을 연결할 테이블까지 준비합니다.
