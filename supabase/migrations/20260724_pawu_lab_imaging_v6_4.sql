alter table if exists public.hospital_staff
  add column if not exists permissions jsonb not null default '{}'::jsonb;

update public.hospital_staff
set permissions =
  coalesce(permissions, '{}'::jsonb) ||
  case
    when coalesce(role, '') = 'owner' then
      '{"view_lab":true,"write_lab":true,"finalize_lab":true}'::jsonb
    when coalesce(role, '') = 'veterinarian' then
      '{"view_lab":true,"write_lab":true,"finalize_lab":true}'::jsonb
    when coalesce(role, '') in ('nurse','receptionist') then
      '{"view_lab":true,"write_lab":true,"finalize_lab":false}'::jsonb
    else
      '{"view_lab":true,"write_lab":false,"finalize_lab":false}'::jsonb
  end;

create table if not exists public.lab_orders (
  id bigint generated by default as identity primary key,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  pet_id bigint not null references public.pets(id) on delete restrict,
  emr_record_id bigint references public.emr_records(id) on delete set null,
  reservation_id bigint references public.reservations(id) on delete set null,
  category text not null,
  test_name text not null,
  status text not null default 'ordered'
    check (status in ('ordered','collected','processing','completed','finalized','cancelled')),
  priority text not null default 'routine'
    check (priority in ('routine','urgent','stat')),
  specimen_type text,
  clinical_note text,
  external_lab_name text,
  interpretation text,
  guardian_summary text,
  guardian_visible boolean not null default false,
  requested_by uuid references public.profiles(id) on delete set null,
  finalized_by uuid references auth.users(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  requested_at timestamptz not null default now(),
  collected_at timestamptz,
  completed_at timestamptz,
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

