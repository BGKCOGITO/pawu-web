);

create index if not exists lab_result_values_order_sort_idx
  on public.lab_result_values(lab_order_id, sort_order, id);

create table if not exists public.lab_attachments (
  id bigint generated by default as identity primary key,
  lab_order_id bigint not null references public.lab_orders(id) on delete cascade,
  file_name text not null,
  file_path text not null,
  mime_type text,
  file_size bigint,
  attachment_type text not null default 'other'
    check (attachment_type in ('image','pdf','dicom','other')),
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(lab_order_id, file_path)
);

create index if not exists lab_attachments_order_idx
  on public.lab_attachments(lab_order_id, created_at desc);

create table if not exists public.lab_audit_logs (
  id bigint generated by default as identity primary key,
  lab_order_id bigint not null references public.lab_orders(id) on delete cascade,
  action text not null
    check (action in ('created','updated','finalized','reopened','file_added','file_deleted')),
  reason text,
  actor_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists lab_audit_logs_order_idx
  on public.lab_audit_logs(lab_order_id, created_at desc);

create or replace function public.pawu_reopen_lab_order(
  p_hospital_id bigint,
  p_order_id bigint,
  p_actor_user_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
begin
  if coalesce(trim(p_reason), '') = '' then
    raise exception '재개 사유가 필요합니다.';
  end if;

  select status
  into v_status
  from public.lab_orders
  where id = p_order_id
    and hospital_id = p_hospital_id
  for update;

  if not found then
    raise exception '검사 주문을 찾지 못했습니다.';
  end if;

  if v_status <> 'finalized' then
    raise exception '확정된 검사만 다시 열 수 있습니다.';
  end if;

  update public.lab_orders
  set status = 'completed',
      finalized_at = null,
      finalized_by = null,
      updated_by = p_actor_user_id,
      updated_at = now()
  where id = p_order_id;

  insert into public.lab_audit_logs(
    lab_order_id, action, reason, actor_user_id
  )
  values(
    p_order_id, 'reopened', p_reason, p_actor_user_id
  );

  return jsonb_build_object('order_id', p_order_id, 'status', 'completed');
end;
$$;

