drop policy if exists "hospital and guardian read lab orders" on public.lab_orders;
create policy "hospital and guardian read lab orders"
on public.lab_orders for select to authenticated
using (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = lab_orders.hospital_id
      and hs.is_active = true
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = lab_orders.hospital_id
  )
  or exists(
    select 1 from public.pets p
    where p.id = lab_orders.pet_id
      and p.user_id = auth.uid()
      and lab_orders.status = 'finalized'
      and lab_orders.guardian_visible = true
  )
);

