drop policy if exists "participants read conversations" on public.chat_conversations;
create policy "participants read conversations"
on public.chat_conversations for select
to authenticated
using (
  guardian_user_id = auth.uid()
  or exists (
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = chat_conversations.hospital_id
      and hs.is_active = true
  )
  or exists (
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = chat_conversations.hospital_id
  )
);

drop policy if exists "participants read messages" on public.chat_messages;
create policy "participants read messages"
on public.chat_messages for select
to authenticated
using (
  exists (
    select 1 from public.chat_conversations cc
    where cc.id = chat_messages.conversation_id
      and (
        cc.guardian_user_id = auth.uid()
        or exists (
          select 1 from public.hospital_staff hs
          where hs.user_id = auth.uid()
            and hs.hospital_id = cc.hospital_id
            and hs.is_active = true
        )
        or exists (
          select 1 from public.hospital_admins ha
          where ha.user_id = auth.uid()
            and ha.hospital_id = cc.hospital_id
        )
      )
  )
);

drop policy if exists "users read own ai symptom sessions" on public.ai_symptom_sessions;
create policy "users read own ai symptom sessions"
on public.ai_symptom_sessions for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "users insert own ai symptom sessions" on public.ai_symptom_sessions;
create policy "users insert own ai symptom sessions"
on public.ai_symptom_sessions for insert
to authenticated
with check (user_id = auth.uid());

