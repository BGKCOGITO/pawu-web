alter table public.medical_records
  add column if not exists ai_summary_updated_at timestamptz;

create table if not exists public.chat_conversations (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null unique references public.reservations(id) on delete cascade,
  guardian_user_id uuid not null references auth.users(id) on delete cascade,
  hospital_id bigint not null references public.hospitals(id) on delete cascade,
  pet_id bigint references public.pets(id) on delete set null,
  status text not null default 'open' check (status in ('open','closed','blocked')),
  last_message_at timestamptz,
  last_message_preview text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  sender_user_id uuid not null references auth.users(id) on delete cascade,
  sender_type text not null check (sender_type in ('guardian','hospital','system')),
  message_type text not null default 'text' check (message_type in ('text','image','video','file','system')),
  content text,
  file_name text,
  file_path text,
  public_url text,
  mime_type text,
  file_size bigint,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists chat_conversations_guardian_idx
  on public.chat_conversations(guardian_user_id,last_message_at desc);

create index if not exists chat_conversations_hospital_idx
  on public.chat_conversations(hospital_id,last_message_at desc);

create index if not exists chat_messages_conversation_idx
  on public.chat_messages(conversation_id,created_at);

create table if not exists public.ai_symptom_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  pet_id bigint references public.pets(id) on delete set null,
  species text,
  symptom_text text not null,
  guide_level text not null check (guide_level in ('observe','urgent','emergency')),
  guide_result jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.hospital_verification_requests (
  id bigint generated by default as identity primary key,
  applicant_user_id uuid references auth.users(id) on delete set null,
  hospital_name text not null,
  business_number text,
  veterinarian_name text,
  license_number text,
  status text not null default 'pending'
    check (status in ('pending','reviewing','approved','needs_documents','rejected')),
  risk_score integer not null default 0 check (risk_score between 0 and 100),
  risk_reasons text[] not null default '{}',
  document_paths text[] not null default '{}',
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

