drop policy if exists "hospital members read emr records" on public.emr_records;
create policy "hospital members read emr records"
on public.emr_records for select to authenticated
using (
  exists(
    select 1 from public.hospital_staff hs
    where hs.user_id = auth.uid()
      and hs.hospital_id = emr_records.hospital_id
      and hs.is_active = true
  )
  or exists(
    select 1 from public.hospital_admins ha
    where ha.user_id = auth.uid()
      and ha.hospital_id = emr_records.hospital_id
  )
  or exists(
    select 1 from public.pets p
    where p.id = emr_records.pet_id
      and p.user_id = auth.uid()
      and emr_records.status = 'finalized'
  )
);

drop policy if exists "guardians read finalized diagnoses" on public.emr_diagnoses;
create policy "guardians read finalized diagnoses"
on public.emr_diagnoses for select to authenticated
using (
  exists(
    select 1
    from public.emr_records er
    join public.pets p on p.id = er.pet_id
    where er.id = emr_diagnoses.emr_record_id
      and (
        exists(
          select 1 from public.hospital_staff hs
          where hs.user_id = auth.uid()
            and hs.hospital_id = er.hospital_id
            and hs.is_active = true
        )
        or exists(
          select 1 from public.hospital_admins ha
          where ha.user_id = auth.uid()
            and ha.hospital_id = er.hospital_id
        )
        or (p.user_id = auth.uid() and er.status = 'finalized')
      )
  )
);

